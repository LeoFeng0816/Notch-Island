import AppKit
import Combine
import UniformTypeIdentifiers

// Clipboard history: off until the user turns it on, kept only on this Mac,
// skips password-manager / concealed / transient content, and is deleted
// after the chosen retention (default 3 days). Contents are never logged.

struct ClipboardItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var date: Date
    var text: String?
    /// PNG file name inside the store directory.
    var imageFile: String?
    var imageWidth: Double?
    var imageHeight: Double?
    /// file:// URLs as strings.
    var files: [String]?

    /// Short single-line preview for the list.
    var preview: String {
        switch kind {
        case .text:
            let single = (text ?? "").replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
            return String(single.prefix(120))
        case .image:
            if let w = imageWidth, let h = imageHeight { return "\(Int(w)) × \(Int(h))" }
            return ""
        case .files:
            let names = (files ?? []).compactMap { URL(string: $0)?.lastPathComponent }
            return names.prefix(3).joined(separator: ", ") + (names.count > 3 ? " +\(names.count - 3)" : "")
        }
    }
}

enum ClipboardRetention: Int, CaseIterable, Identifiable, Codable {
    case oneDay = 1, threeDays = 3, sevenDays = 7, thirtyDays = 30
    var id: Int { rawValue }
    var seconds: TimeInterval { TimeInterval(rawValue) * 86_400 }
    static let `default`: ClipboardRetention = .threeDays
}

/// What may be recorded. Pure, unit-tested.
enum ClipboardPolicy {
    /// nspasteboard.org markers used by password managers and utilities for
    /// content that must not be kept in history, plus known vendor types.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
        "com.apple.is-remote-clipboard.secure", // defensive
    ]

    /// Copies made while one of these apps is in front are never recorded.
    static let passwordManagerBundles: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords",
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc", "in.sinew.Enpass-Desktop", "me.proton.pass.electron",
        "com.keepersecurity.passwordmanager", "com.nordpass.macos.NordPass", "com.roboform.mac",
    ]

    /// Our own writes carry this type so they are not recorded again.
    static let ownMarkerType = "local.notchisland.clipboard-paste"

    static let maxItems = 50
    static let maxTextBytes = 100_000           // longer texts are not kept (never truncated: pasting must be exact)
    static let maxImageBytes = 8_000_000         // PNG size limit per image
    static let maxFiles = 20

    static func shouldIgnore(types: [String], frontmostBundleID: String?) -> Bool {
        if types.contains(where: { ignoredTypes.contains($0) || $0 == ownMarkerType }) { return true }
        if let id = frontmostBundleID, passwordManagerBundles.contains(id) { return true }
        return false
    }
}

/// Local, size-limited history. Only touches the pasteboard it is given.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var enabled: Bool
    @Published private(set) var retention: ClipboardRetention

    let directory: URL
    private let defaults: UserDefaults
    private let pasteboard: NSPasteboard
    private let now: () -> Date
    private let frontmostBundleID: () -> String?
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var pollTimer: Timer?
    private var purgeTimer: Timer?

    private enum Key {
        static let enabled = "NotchIsland.clipboard.enabled"
        static let retention = "NotchIsland.clipboard.retentionDays"
    }

    nonisolated static var defaultDirectory: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        return base.appendingPathComponent("NotchIsland/Clipboard", isDirectory: true)
    }

    init(defaults: UserDefaults = .standard, pasteboard: NSPasteboard = .general,
         directory: URL = ClipboardStore.defaultDirectory, now: @escaping () -> Date = Date.init,
         frontmostBundleID: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        self.defaults = defaults
        self.pasteboard = pasteboard
        self.directory = directory
        self.now = now
        self.frontmostBundleID = frontmostBundleID
        enabled = defaults.bool(forKey: Key.enabled)
        retention = ClipboardRetention(rawValue: defaults.integer(forKey: Key.retention)) ?? .default
        // Don't record whatever was already on the clipboard before history started.
        lastChangeCount = pasteboard.changeCount
        load()
        purge()
    }

    // MARK: Settings

    func setEnabled(_ on: Bool) {
        enabled = on
        defaults.set(on, forKey: Key.enabled)
        lastChangeCount = pasteboard.changeCount
        if on { startMonitoring() } else { stopMonitoring() }
    }

    func setRetention(_ value: ClipboardRetention) {
        retention = value
        defaults.set(value.rawValue, forKey: Key.retention)
        purge()
    }

    // MARK: Monitoring (polling changeCount is the only public mechanism)

    func startMonitoring() {
        guard enabled, pollTimer == nil else { return }
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { _ = self?.checkPasteboard() }
        }
        purgeTimer = Timer.scheduledTimer(withTimeInterval: 3600, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.purge() }
        }
    }

    func stopMonitoring() {
        pollTimer?.invalidate(); pollTimer = nil
        purgeTimer?.invalidate(); purgeTimer = nil
    }

    /// Records a new clipboard change if allowed. Returns the stored item (tests).
    @discardableResult
    func checkPasteboard() -> ClipboardItem? {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count
        guard enabled, count != ownChangeCount else { return nil }
        let types = (pasteboard.types ?? []).map(\.rawValue)
        guard !ClipboardPolicy.shouldIgnore(types: types, frontmostBundleID: frontmostBundleID()) else { return nil }
        guard let item = makeItem() else { return nil }
        insert(item)
        return item
    }

    private func makeItem() -> ClipboardItem? {
        let date = now()
        // Files first (Finder copies also carry a text name).
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            guard urls.count <= ClipboardPolicy.maxFiles else { return nil }
            return ClipboardItem(kind: .files, date: date, files: urls.map(\.absoluteString))
        }
        if let image = NSImage(pasteboard: pasteboard), pasteboard.canReadItem(withDataConformingToTypes: [UTType.image.identifier]),
           let png = Self.pngData(image), png.count <= ClipboardPolicy.maxImageBytes {
            let name = UUID().uuidString + ".png"
            guard prepareDirectory(), (try? png.write(to: directory.appendingPathComponent(name), options: [.atomic])) != nil else { return nil }
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: directory.appendingPathComponent(name).path)
            return ClipboardItem(kind: .image, date: date, imageFile: name,
                                 imageWidth: Double(image.size.width), imageHeight: Double(image.size.height))
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= ClipboardPolicy.maxTextBytes else { return nil }
            return ClipboardItem(kind: .text, date: date, text: text)
        }
        return nil
    }

    static func pngData(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func insert(_ item: ClipboardItem) {
        // Same text copied again → move to top instead of duplicating.
        if item.kind == .text, let index = items.firstIndex(where: { $0.kind == .text && $0.text == item.text }) {
            items.remove(at: index)
        }
        items.insert(item, at: 0)
        while items.count > ClipboardPolicy.maxItems { deleteFiles(of: items.removeLast()) }
        save()
    }

    // MARK: Using an item

    /// Puts the item back on the clipboard (marked as ours so it isn't recorded again).
    @discardableResult
    func copyToPasteboard(_ item: ClipboardItem, pasteboard target: NSPasteboard? = nil) -> Bool {
        let board = target ?? pasteboard
        board.clearContents()
        var ok = false
        switch item.kind {
        case .text:
            ok = item.text.map { board.setString($0, forType: .string) } ?? false
        case .image:
            if let name = item.imageFile, let image = NSImage(contentsOf: directory.appendingPathComponent(name)) {
                ok = board.writeObjects([image])
            }
        case .files:
            let urls = (item.files ?? []).compactMap(URL.init(string:)).filter { FileManager.default.fileExists(atPath: $0.path) }
            ok = !urls.isEmpty && board.writeObjects(urls as [NSURL])
        }
        if ok {
            board.setData(Data(), forType: NSPasteboard.PasteboardType(ClipboardPolicy.ownMarkerType))
            if board == pasteboard { ownChangeCount = board.changeCount; lastChangeCount = board.changeCount }
        }
        return ok
    }

    func image(for item: ClipboardItem) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: directory.appendingPathComponent($0)) }
    }

    // MARK: Retention

    func purge() {
        let cutoff = now().addingTimeInterval(-retention.seconds)
        let expired = items.filter { $0.date < cutoff }
        guard !expired.isEmpty || orphanFiles().count > 0 else { return }
        expired.forEach(deleteFiles)
        items.removeAll { $0.date < cutoff }
        orphanFiles().forEach { try? FileManager.default.removeItem(at: $0) }
        save()
    }

    func clear() {
        items.forEach(deleteFiles)
        items = []
        orphanFiles().forEach { try? FileManager.default.removeItem(at: $0) }
        save()
    }

    // MARK: Persistence (index.json + PNGs, owner-only permissions)

    private var indexURL: URL { directory.appendingPathComponent("index.json") }

    private func prepareDirectory() -> Bool {
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                    attributes: [.posixPermissions: 0o700])
            return true
        } catch { return false }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard prepareDirectory() else { return }
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: indexURL, options: [.atomic])
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: indexURL.path)
        }
    }

    private func deleteFiles(of item: ClipboardItem) {
        if let name = item.imageFile { try? FileManager.default.removeItem(at: directory.appendingPathComponent(name)) }
    }

    private func orphanFiles() -> [URL] {
        let known = Set(items.compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
        return files.filter { $0.pathExtension == "png" && !known.contains($0.lastPathComponent) }
    }
}

// MARK: - Paste into the app that was in front

/// Pastes by sending ⌘V to the app that was frontmost before the island was
/// used. Needs the "post events" permission (requested only from the user's
/// action); without it the item is just copied and the UI says so.
enum ClipboardPaste {
    enum Outcome: Equatable {
        /// ⌘V was sent to this app (macOS doesn't report whether the app accepted it).
        case pasted(appName: String)
        case copiedOnly(Reason)
        case failed
    }

    enum Reason: Equatable { case noTarget, needsPermission, focusLost }

    /// Pure decision (tests): what can be done before touching the system.
    static func plan(copied: Bool, hasTarget: Bool, targetIsSelf: Bool, targetTerminated: Bool, canPostEvents: Bool) -> Outcome? {
        guard copied else { return .failed }
        guard hasTarget, !targetIsSelf, !targetTerminated else { return .copiedOnly(.noTarget) }
        guard canPostEvents else { return .copiedOnly(.needsPermission) }
        return nil // go ahead: activate + ⌘V
    }

    /// Re-activates `target`, waits until it is frontmost, then posts ⌘V.
    @MainActor
    static func paste(into target: NSRunningApplication, completion: @escaping (Outcome) -> Void) {
        let name = target.localizedName ?? target.bundleIdentifier ?? "?"
        if NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
            target.activate()
        }
        var attempts = 0
        func attempt() {
            attempts += 1
            if NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier {
                postCommandV()
                completion(.pasted(appName: name))
            } else if attempts < 10 {
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { attempt() }
            } else {
                completion(.copiedOnly(.focusLost))
            }
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { attempt() }
    }

    static let vKeyCode: CGKeyCode = 9

    static func commandVEvents() -> [CGEvent] {
        let source = CGEventSource(stateID: .combinedSessionState)
        return [true, false].compactMap { down in
            let event = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: down)
            event?.flags = .maskCommand
            return event
        }
    }

    private static func postCommandV() {
        for event in commandVEvents() { event.post(tap: .cghidEventTap) }
    }
}
